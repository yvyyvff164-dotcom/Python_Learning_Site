function prediction(index, seed) {
    const draw = random(seed);
    const a = draw(3,15), b = draw(2,6), c = draw(1,8);
    const prompt = t('Python қандай сан шығарады? Кодты ойша орындап, жауапты таңдаңыз.', 'Какое число выведет Python? Проследите выполнение программы и выберите ответ.');
    const make = (id,title,lesson,code,answer,alternatives,hint,why) => {
        const options = [...new Set([answer,...alternatives])];
        for (let extra = 1; options.length < 4; extra++) if (!options.includes(answer+extra)) options.push(answer+extra);
        return {id,title,lesson,code,answer,options: shuffled(options.slice(0,4), seed ^ 0x59a71),prompt,hint,why};
    };
    if (index === 0) return make('values',t('Айнымалының ізімен','По следам переменной'),'/variables',
        'x = '+a+'\nx = x * '+b+'\nx = x - '+c+'\nprint(x)',a*b-c,[a*b,a*b+c,(a-c)*b],
        t('Әр жолдан кейін x мәнін жазып отырыңыз.', 'Запишите значение x после каждой строки.'),
        t('Көбейтуден кейін x = '+a*b+'. Содан кейін '+c+' азаяды.', 'После умножения x = '+a*b+'. Затем вычитается '+c+'.'));
    if (index === 1) {
        const threshold = draw(5,13);
        const answer = a >= threshold ? a+b : a-c;
        return make('branch',t('Қай тармақ іске қосылады?','Какая ветка сработает?'),'/conditions',
            'score = '+a+'\nif score >= '+threshold+':\n    score += '+b+'\nelse:\n    score -= '+c+'\nprint(score)',answer,[a,a+b,a-c,a+b-c],
            t('Алдымен >= шартын тексеріңіз. Екі тармақтың біреуі ғана орындалады.', 'Сначала проверьте условие >=. Выполнится одна из двух веток.'),
            t('Бастапқы мән '+a+'. Шарт '+(a>=threshold?'ақиқат':'жалған')+', сондықтан нәтиже '+answer+'.', 'Изначально score = '+a+'. Условие '+(a>=threshold?'истинно':'ложно')+', поэтому получится '+answer+'.'));
    }
    if (index === 2) {
        const total = b*(b+1)/2;
        return make('loop',t('Жинақтауыш','Накопитель'),'/loops','total = '+c+'\nfor i in range(1, '+(b+1)+'):\n    total += i\nprint(total)',c+total,
            [total,c+total+b+1,c+total-b],t('range соңғы шекараны қоспайды. total бастапқыда нөл болмауы мүмкін.', 'Правая граница range исключена. Учтите начальное значение total.'),
            t('1-ден '+b+'-ге дейінгі сандардың қосындысы '+total+'. Оған '+c+' қосылады.', 'Сумма чисел от 1 до '+b+' равна '+total+'. К ней прибавляется начальное значение '+c+'.'));
    }
    const values = [a,a+b,a+b+c];
    const i = draw(0,2);
    return make('index',t('Тізімнің ұяшығы','Ячейка списка'),'/arrays1','values = ['+values.join(', ')+']\nprint(values['+i+'] + '+b+')',values[i]+b,
        [values[i],values[(i+1)%3]+b,values[(i+2)%3]+b],t('Бірінші элементтің индексі 0. Қосуды элементті таңдағаннан кейін орындаңыз.', 'Индекс первого элемента равен 0. Сложение выполняется после выбора элемента.'),
        t(i+' индексіндегі мән '+values[i]+'. Оған '+b+' қосылады.', 'По индексу '+i+' лежит '+values[i]+'. К этому значению прибавляется '+b+'.'));
}

